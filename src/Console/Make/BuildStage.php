<?php

namespace Streams\Sdk\Console\Make;

use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;
use PhpParser\Node\Stmt\Class_;
use PhpParser\Node\Stmt\ClassMethod;
use PhpParser\Node\Stmt\Namespace_;
use SebastianBergmann\Diff\Differ;
use SebastianBergmann\Diff\Output\UnifiedDiffOutputBuilder;
use Streams\Sdk\Console\Support\PhpEditor;
use Streams\Sdk\Support\AppTree;

/**
 * Compares the app JSON tree with the code.
 *
 * Files are generated into a MemoryTree first. The plan (unified diff,
 * created, modified, skipped, unapplied) is taken from that tree. Apply
 * writes only created and modified files. It never deletes: a node removed
 * from the tree leaves its file on disk and lists it as skipped. An edit
 * that cannot be applied is reported with the node path, file, and reason,
 * and that file is left untouched.
 */
class BuildStage
{
    public const MARKER = 'Generated by streams/sdk';

    protected ?MemoryTree $memory = null;

    public function __construct(protected Paths $paths) {}

    /**
     * Build the in-memory tree and diff it against $outputRoot.
     *
     * $only limits the plan to one dot path and its descendants.
     */
    public function plan(AppTree $tree, ?string $only, string $outputRoot): BuildPlan
    {
        $this->memory = $this->compile($tree, $only);

        $plan = new BuildPlan;
        $compiled = [];

        foreach ($this->memory->files() as $file) {
            $compiled[$file->nodePath] = $file->relative;
            $absolute = $this->absolute($outputRoot, $file->relative);
            $actual = is_file($absolute) ? (string) file_get_contents($absolute) : null;

            if ($actual === null) {
                $plan->created[] = $file->relative;
                $plan->diffs[$file->relative] = $this->diff($file->relative, '', $file->contents);

                continue;
            }

            if ($actual === $file->contents) {
                continue;
            }

            $failures = $this->editFailures($actual, $file);

            if ($failures !== []) {
                foreach ($failures as $reason) {
                    $plan->unapplied[] = [
                        'path' => $file->nodePath,
                        'file' => $file->relative,
                        'reason' => $reason,
                    ];
                }

                continue;
            }

            $plan->modified[] = $file->relative;
            $plan->diffs[$file->relative] = $this->diff($file->relative, $actual, $file->contents);
        }

        foreach ($this->managedFiles($outputRoot) as $relative => $nodePath) {
            if (isset($compiled[$nodePath]) || ! $this->inScope($nodePath, $only)) {
                continue;
            }

            $plan->skipped[] = $relative;
        }

        sort($plan->created);
        sort($plan->modified);
        sort($plan->skipped);

        usort($plan->unapplied, function (array $left, array $right): int {
            return [$left['path'], $left['file'], $left['reason']] <=> [$right['path'], $right['file'], $right['reason']];
        });

        return $plan;
    }

    /**
     * Write the planned adds and edits. Skipped and unapplied files stay as they are.
     */
    public function apply(BuildPlan $plan, string $outputRoot): void
    {
        if ($this->memory === null) {
            throw new \RuntimeException('BuildStage::plan() must run before apply().');
        }

        $contents = [];

        foreach ($this->memory->files() as $file) {
            $contents[$file->relative] = $file->contents;
        }

        foreach (array_merge($plan->created, $plan->modified) as $relative) {
            if (! isset($contents[$relative])) {
                continue;
            }

            $absolute = $this->absolute($outputRoot, $relative);

            File::ensureDirectoryExists(dirname($absolute));
            File::put($absolute, $contents[$relative]);
        }
    }

    protected function compile(AppTree $tree, ?string $only): MemoryTree
    {
        $memory = new MemoryTree;

        foreach ($tree->types() as $path => $type) {
            if (! in_array($type, Paths::FILE_TYPES, true) || ! $this->inScope($path, $only)) {
                continue;
            }

            $domain = Str::studly(explode('.', $path)[0]);
            $class = $this->className($tree, $path, $type);
            $relative = $this->paths->resolve($type, $domain, $class);

            if ($relative === null) {
                continue;
            }

            $node = $tree->node($path);
            $label = $this->label($node, $path);

            $memory->add(new CompiledFile(
                $path,
                $relative,
                $this->render($this->paths->namespaceFor($relative), $class, $path, $label),
                $class,
            ));
        }

        return $memory;
    }

    /**
     * Panel classes use the reference suffix (PeoplePanelResource). Every
     * other code-bearing node uses the StudlyCase of its full dot path, which
     * is unique across the tree.
     */
    protected function className(AppTree $tree, string $path, string $type): string
    {
        $class = $tree->classForPath($path);

        if ($type === 'panel') {
            return $class.'Resource';
        }

        return $class;
    }

    /**
     * @param  array<string, mixed>  $node
     */
    protected function label(array $node, string $path): string
    {
        foreach (['label', 'title', 'name', 'handle'] as $key) {
            if (isset($node[$key]) && is_string($node[$key]) && $node[$key] !== '') {
                return $node[$key];
            }
        }

        return $path;
    }

    protected function render(string $namespace, string $class, string $nodePath, string $label): string
    {
        $marker = self::MARKER;
        $exportedPath = var_export($nodePath, true);
        $exportedLabel = var_export($label, true);

        return <<<PHP
<?php

namespace {$namespace};

/**
 * {$marker}.
 * Node: {$nodePath}
 */
class {$class}
{
    public function nodePath(): string
    {
        return {$exportedPath};
    }

    public function label(): string
    {
        return {$exportedLabel};
    }
}

PHP;
    }

    /**
     * Reasons the file cannot be edited into the generated tree.
     * An empty list means both edits (declare class, set label) can apply.
     *
     * @return list<string>
     */
    protected function editFailures(string $actual, CompiledFile $file): array
    {
        $declare = 'declare class '.$file->class;
        $label = 'set label';

        if (! str_contains($actual, self::MARKER)) {
            return [
                $this->failure($declare, 'file is not managed by streams:make'),
            ];
        }

        try {
            $editor = PhpEditor::fromString($actual, $file->relative);
        } catch (\Throwable) {
            return [
                $this->failure($declare, 'file could not be parsed'),
                $this->failure($label, 'file could not be parsed'),
            ];
        }

        [$hasClass, $hasLabel] = $this->inspect($editor, $file->class);
        $failures = [];

        if (! $hasClass) {
            $failures[] = $this->failure($declare, 'no class declaration found');
        }

        if (! $hasLabel) {
            $failures[] = $this->failure($label, 'method label() was not found');
        }

        return $failures;
    }

    protected function failure(string $edit, string $reason): string
    {
        return "cannot apply edit [{$edit}]: {$reason}";
    }

    /**
     * @return array{0: bool, 1: bool}
     */
    protected function inspect(PhpEditor $editor, string $class): array
    {
        $hasClass = false;
        $hasLabel = false;

        $walk = function (array $nodes) use (&$walk, &$hasClass, &$hasLabel, $class): void {
            foreach ($nodes as $node) {
                if ($node instanceof Class_ && $node->name !== null && $node->name->toString() === $class) {
                    $hasClass = true;

                    foreach ($node->stmts ?? [] as $stmt) {
                        if ($stmt instanceof ClassMethod && $stmt->name->toString() === 'label') {
                            $hasLabel = true;
                        }
                    }
                }

                if ($node instanceof Namespace_ && is_array($node->stmts)) {
                    $walk($node->stmts);
                }
            }
        };

        $walk($editor->statements());

        return [$hasClass, $hasLabel];
    }

    /**
     * Generated files under the managed root, keyed by relative path.
     * The value is the dot path recorded in the file's Node line.
     *
     * @return array<string, string>
     */
    protected function managedFiles(string $outputRoot): array
    {
        $managed = $this->absolute($outputRoot, $this->paths->managedRoot());

        if (! is_dir($managed)) {
            return [];
        }

        $found = [];
        $prefix = rtrim(str_replace('\\', '/', $outputRoot), '/').'/';

        foreach (File::allFiles($managed) as $file) {
            $absolute = str_replace('\\', '/', $file->getPathname());

            if (! str_starts_with($absolute, $prefix) || $file->getExtension() !== 'php') {
                continue;
            }

            $contents = $file->getContents();

            if (! is_string($contents) || ! preg_match('/^[ \t]*\*[ \t]*Node:[ \t]*(\S+)/m', $contents, $matches)) {
                continue;
            }

            $found[substr($absolute, strlen($prefix))] = $matches[1];
        }

        return $found;
    }

    protected function inScope(string $nodePath, ?string $only): bool
    {
        if ($only === null || $only === '') {
            return true;
        }

        return $nodePath === $only || str_starts_with($nodePath, $only.'.');
    }

    protected function absolute(string $outputRoot, string $relative): string
    {
        return rtrim($outputRoot, '/').'/'.ltrim($relative, '/');
    }

    protected function diff(string $path, string $from, string $to): string
    {
        $differ = new Differ(new UnifiedDiffOutputBuilder("--- {$path}\n+++ {$path}\n"));

        return $differ->diff($from, $to);
    }
}
