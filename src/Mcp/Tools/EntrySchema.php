<?php

namespace Streams\Sdk\Mcp\Tools;

use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\Support\Facades\File;
use Laravel\Mcp\Request;
use Laravel\Mcp\Response;
use Laravel\Mcp\ResponseFactory;
use Laravel\Mcp\Server\Attributes\Description;
use Laravel\Mcp\Server\Attributes\Name;
use Laravel\Mcp\Server\Attributes\Title;
use Laravel\Mcp\Server\Tools\Annotations\IsIdempotent;
use Laravel\Mcp\Server\Tools\Annotations\IsOpenWorld;
use Laravel\Mcp\Server\Tools\Annotations\IsReadOnly;
use Streams\Sdk\Mcp\Tool;
use Streams\Sdk\Support\StreamFacts;
use Throwable;

/**
 * The shape of a valid entry, as Core generates it. This is what `streams:schema`
 * writes and what a client or agent should conform to.
 */
#[Name('entry-schema')]
#[Title('Entry JSON Schema for a stream')]
#[Description('The JSON Schema for one stream\'s entries, generated by the same code as `php artisan streams:schema`: a tag object ("tag": "App\\\\Entry\\\\People") wrapping the field object, with types and required fields taken from the definition. Use it to conform data before writing it, or to generate a client type. If the file on disk is older than the definition, say so and re-run `php artisan streams:schema --include={stream}`.')]
#[IsReadOnly]
#[IsIdempotent]
#[IsOpenWorld(false)]
class EntrySchema extends Tool
{
    public function handle(Request $request): Response|ResponseFactory
    {
        $validated = $request->validate([
            'stream' => ['required', 'string'],
        ], [
            'stream.required' => 'Pass a stream id, for example {"stream": "people"}.',
        ]);

        $stream = $this->stream((string) $validated['stream']);

        if ($stream === null) {
            return $this->unknownStream((string) $validated['stream']);
        }

        try {
            $schema = $stream->schema();
        } catch (Throwable $e) {
            return Response::error('The ['.$stream->id.'] entry schema could not be generated: '.$e->getMessage());
        }

        $written = $this->schemaFile((string) $stream->id);

        return $this->data([
            'stream' => (string) $stream->id,
            'tag' => (string) $stream->tag(),
            'schema' => $schema,
            'file' => $written,
            'stale' => $written === null,
            'generate' => 'php artisan streams:schema --include='.$stream->id,
        ]);
    }

    /**
     * Where `streams:schema` writes by default, if it has run yet.
     */
    protected function schemaFile(string $id): ?string
    {
        foreach ([$id.'.schema.json', $id.'/schema.json'] as $candidate) {
            foreach (['schemas/'.$candidate, $candidate] as $relative) {
                if (is_file(base_path($relative))) {
                    return StreamFacts::relative(base_path($relative));
                }
            }
        }

        return null;
    }

    public function schema(JsonSchema $schema): array
    {
        return [
            'stream' => $schema->string()->description('Stream id.')->required(),
        ];
    }
}
