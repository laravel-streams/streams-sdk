<?php

namespace Streams\Sdk\Console\Onboard;

use Illuminate\Support\Str;
use Streams\Sdk\Support\StreamSourceValidator;

/**
 * Emits ADR-0009 domain plumbing from a plural domain name.
 *
 * Writes Entry model, Streams repository, lang locales, core stream
 * definition (streams/{handle}.json), and an app-tree stream node.
 * Does not emit UI, actions, or business rules.
 */
final class DomainScaffold
{
    /** @var list<string> */
    public const LOCALES = ['en', 'es', 'pt_BR'];

    public function __construct(
        protected StreamSourceValidator $validator = new StreamSourceValidator,
    ) {}

    /**
     * @return array{
     *     domain: string,
     *     handle: string,
     *     entity: string,
     *     files: list<string>,
     *     skipped: list<string>,
     *     stream: array<string, mixed>,
     *     validation: array{valid: bool, errors: array<int, string>, warnings: array<int, string>, source_type: string|null}
     * }
     */
    public function emit(string $domain, string $basePath, bool $force = false): array
    {
        $domain = Str::studly($domain);
        $handle = Str::snake($domain);
        $entity = Str::studly(Str::singular($domain));
        $base = rtrim($basePath, '/');

        $modelFqcn = "App\\Domains\\{$domain}\\Models\\{$entity}";
        $repositoryFqcn = "App\\Domains\\{$domain}\\Repositories\\{$domain}";

        $files = [];
        $skipped = [];

        $this->write($base."/app/Domains/{$domain}/Models/{$entity}.php", $this->modelPhp($domain, $entity), $force, $files, $skipped);
        $this->write($base."/app/Domains/{$domain}/Repositories/{$domain}.php", $this->repositoryPhp($domain), $force, $files, $skipped);

        foreach (self::LOCALES as $locale) {
            $this->write(
                $base."/lang/{$locale}/domains/{$handle}.php",
                $this->langPhp($handle, $entity),
                $force,
                $files,
                $skipped,
            );
        }

        $stream = $this->streamDefinition($domain, $handle, $entity, $modelFqcn, $repositoryFqcn);
        $streamPath = $base."/streams/{$handle}.json";
        $this->write($streamPath, json_encode($stream, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n", $force, $files, $skipped);

        $this->ensureAppTree($base, $domain, $handle, $force, $files, $skipped);

        $validation = $this->validator->validate($stream);

        return [
            'domain' => $domain,
            'handle' => $handle,
            'entity' => $entity,
            'files' => $files,
            'skipped' => $skipped,
            'stream' => $stream,
            'validation' => $validation,
        ];
    }

    /**
     * @param  list<string>  $files
     * @param  list<string>  $skipped
     */
    protected function write(string $path, string $contents, bool $force, array &$files, array &$skipped): void
    {
        if (is_file($path) && ! $force) {
            $skipped[] = $path;

            return;
        }

        $dir = dirname($path);
        if (! is_dir($dir) && ! mkdir($dir, 0777, true) && ! is_dir($dir)) {
            throw new \RuntimeException("Unable to create directory [{$dir}].");
        }

        if (file_put_contents($path, $contents) === false) {
            throw new \RuntimeException("Unable to write [{$path}].");
        }

        $files[] = $path;
    }

    /**
     * @param  list<string>  $files
     * @param  list<string>  $skipped
     */
    protected function ensureAppTree(string $base, string $domain, string $handle, bool $force, array &$files, array &$skipped): void
    {
        $path = $base.'/streams.json';
        $ref = "streams/{$handle}.json";

        if (! is_file($path)) {
            $tree = [
                '$schema' => 'https://streams.dev/schema/app.schema.json',
                'name' => $domain,
                'description' => "{$domain} app tree (generated by streams:onboard).",
                'streams' => [
                    $handle => [
                        '$ref' => $ref,
                    ],
                ],
            ];
            $this->write($path, json_encode($tree, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n", true, $files, $skipped);

            return;
        }

        $decoded = json_decode((string) file_get_contents($path), true);
        if (! is_array($decoded)) {
            throw new \RuntimeException("Invalid JSON in [{$path}].");
        }

        $streams = $decoded['streams'] ?? [];
        if (! is_array($streams)) {
            $streams = [];
        }

        if (array_key_exists($handle, $streams) && ! $force) {
            $skipped[] = $path.'#streams.'.$handle;

            return;
        }

        $streams[$handle] = ['$ref' => $ref];
        $decoded['streams'] = $streams;

        $this->write($path, json_encode($decoded, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n", true, $files, $skipped);
    }

    protected function modelPhp(string $domain, string $entity): string
    {
        return <<<PHP
<?php

namespace App\\Domains\\{$domain}\\Models;

use Streams\\Core\\Entry\\Entry;

/**
 * Streams entry for the {$domain} domain. Plumbing only — no business rules.
 */
class {$entity} extends Entry
{
}

PHP;
    }

    protected function repositoryPhp(string $domain): string
    {
        return <<<PHP
<?php

namespace App\\Domains\\{$domain}\\Repositories;

use Streams\\Core\\Repository\\Repository;

/**
 * Streams repository for the {$domain} domain. Plumbing only — no business rules.
 */
class {$domain} extends Repository
{
}

PHP;
    }

    protected function langPhp(string $handle, string $entity): string
    {
        $label = Str::headline($handle);
        $entityLabel = Str::headline(Str::snake($entity));

        return <<<PHP
<?php

// ADR 0015 — lang/{locale}/domains/{$handle}.php
return [
    'label' => '{$label}',
    'entity' => '{$entityLabel}',
    'fields' => [
        'title' => 'Title',
        'completed' => 'Completed',
        'name' => 'Name',
    ],
    'actions' => [],
    'notifications' => [],
];

PHP;
    }

    /**
     * @return array<string, mixed>
     */
    protected function streamDefinition(
        string $domain,
        string $handle,
        string $entity,
        string $modelFqcn,
        string $repositoryFqcn,
    ): array {
        return [
            '$schema' => 'https://streams.dev/schema/streams.schema.json',
            'id' => $handle,
            'name' => $domain,
            'description' => "{$domain} stream (generated by streams:onboard).",
            'config' => [
                'abstract' => $modelFqcn,
                'repository' => $repositoryFqcn,
                'source' => [
                    'type' => 'filebase',
                    'format' => 'json',
                ],
            ],
            'fields' => $this->defaultFields($handle),
        ];
    }

    /**
     * @return list<array<string, mixed>>
     */
    protected function defaultFields(string $handle): array
    {
        $id = [
            'handle' => 'id',
            'type' => 'uuid',
            'required' => true,
            'unique' => true,
            'config' => [
                'default' => true,
            ],
        ];

        if ($handle === 'todos') {
            return [
                $id,
                [
                    'handle' => 'title',
                    'type' => 'string',
                    'required' => true,
                ],
                [
                    'handle' => 'completed',
                    'type' => 'boolean',
                    'config' => [
                        'default' => false,
                    ],
                ],
            ];
        }

        return [
            $id,
            [
                'handle' => 'name',
                'type' => 'string',
                'required' => true,
            ],
        ];
    }
}
