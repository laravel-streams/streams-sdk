<?php

// Maintainer-only snapshot writer; feature tests never update expectations.
require __DIR__.'/../../../vendor/autoload.php';

use Illuminate\Support\Str;
use Streams\Sdk\Console\Make\ComponentRenderer;
use Streams\Sdk\Console\Make\Paths;
use Streams\Sdk\Support\AppTree;

$tree = AppTree::load(__DIR__.'/streams.json');
$paths = new Paths(Paths::DEFAULTS);
$renderer = new ComponentRenderer($paths);

foreach ($tree->types() as $path => $type) {
    if (! in_array($type, Paths::FILE_TYPES, true)) {
        continue;
    }
    $class = $tree->classForPath($path);
    $relative = $paths->resolve($type, Str::studly(explode('.', $path)[0]), $class);
    $namespace = $paths->namespaceFor($relative);
    $node = $tree->node($path);
    $label = var_export($node['label'] ?? $node['title'] ?? $node['name'] ?? $path, true);
    $exportedPath = var_export($path, true);
    $fallback = <<<PHP
<?php

namespace {$namespace};

use Streams\Sdk\Attributes\Generated;

/**
 * Generated by streams/sdk.
 * Node: {$path}
 */
#[Generated({$exportedPath})]
class {$class}
{
    public function nodePath(): string
    {
        return {$exportedPath};
    }

    public function label(): string
    {
        return {$label};
    }
}

PHP;
    $output = __DIR__.'/../Golden/people-make/'.$relative;
    if (! is_dir(dirname($output))) {
        mkdir(dirname($output), 0777, true);
    }
    file_put_contents($output, $renderer->render($tree, $path, $type, $namespace, $class, $fallback));
}
