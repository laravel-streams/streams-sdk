<?php

namespace Streams\Sdk\Tests\Console\Commands;

use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\File;
use Streams\Sdk\Console\Make\StreamLock;
use Streams\Sdk\Tests\SdkTestCase;

/**
 * streams:make plans an in-memory tree, prints that plan, then adds and
 * edits files. It never deletes, and a dry run reports the same plan as
 * the real run without writing.
 */
class StreamsMakeTest extends SdkTestCase
{
    protected string $fixture;

    protected string $output;

    protected ?string $treeCopy = null;

    protected function setUp(): void
    {
        parent::setUp();

        $this->fixture = dirname(__DIR__, 3).'/resources/schemas/fixtures/people/streams.json';

        $this->output = sys_get_temp_dir().'/streams-sdk-make-'.uniqid();

        config([
            'streams.sdk.make.tree' => $this->fixture,
            'streams.sdk.make.output' => $this->output,
        ]);
    }

    protected function tearDown(): void
    {
        if (is_dir($this->output)) {
            File::deleteDirectory($this->output);
        }

        if ($this->treeCopy !== null && is_dir($this->treeCopy)) {
            File::deleteDirectory($this->treeCopy);
        }

        parent::tearDown();
    }

    public function test_dry_run_prints_a_unified_diff_and_writes_nothing(): void
    {
        $code = Artisan::call('streams:make', [
            '--tree' => $this->fixture,
            '--output' => $this->output,
            '--dry-run' => true,
        ]);

        $output = Artisan::output();

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('--- app/Domains/People/Panel/Tables/PeopleTable.php', $output);
        $this->assertStringContainsString('+++ app/Domains/People/Panel/Tables/PeopleTable.php', $output);
        $this->assertStringContainsString('@@', $output);
        $this->assertStringContainsString('+class PeopleTable', $output);
        $this->assertStringContainsString("+#[Generated('people.table')]", $output);
        $this->assertSame([], $this->phpFiles());
        $this->assertFileDoesNotExist(StreamLock::path($this->output));
    }

    public function test_dry_run_json_matches_the_real_run_plan(): void
    {
        $dry = $this->runJson(['--dry-run' => true]);

        $this->assertSame([], $this->phpFiles());
        $this->assertNotEmpty($dry['created']);
        $this->assertContains('app/Domains/People/Panel/Tables/PeopleTable.php', $dry['created']);
        $this->assertContains('app/Domains/People/Panel/Resources/PeoplePanelResource.php', $dry['created']);
        $this->assertSame([], $dry['modified']);
        $this->assertSame([], $dry['skipped']);
        $this->assertSame([], $dry['unapplied']);
        $this->assertSame([], $dry['conflicts']);
        $this->assertStringContainsString('--- app/Domains/People/Panel/Tables/PeopleTable.php', $dry['diff']);

        $real = $this->runJson();

        $this->assertSame($dry['created'], $real['created']);
        $this->assertSame($dry['modified'], $real['modified']);
        $this->assertSame($dry['skipped'], $real['skipped']);
        $this->assertSame($dry['unapplied'], $real['unapplied']);
        $this->assertSame($dry['conflicts'], $real['conflicts']);
        $this->assertSame($dry['diff'], $real['diff']);
        $this->assertNotEmpty($this->phpFiles());

        $table = File::get($this->output.'/app/Domains/People/Panel/Tables/PeopleTable.php');

        $this->assertStringContainsString('namespace App\\Domains\\People\\Panel\\Tables;', $table);
        $this->assertStringContainsString('use Streams\\Sdk\\Attributes\\Generated;', $table);
        $this->assertStringContainsString('Generated by streams/sdk', $table);
        $this->assertStringContainsString("#[Generated('people.table')]", $table);
        $this->assertStringContainsString("return 'people.table';", $table);
        $this->assertStringContainsString("return 'People table';", $table);

        $lock = json_decode((string) file_get_contents(StreamLock::path($this->output)), true);
        $relative = 'app/Domains/People/Panel/Tables/PeopleTable.php';

        $this->assertSame(StreamLock::hashContents($table), $lock['people.table'][$relative]);
    }

    public function test_a_second_run_with_no_tree_changes_reports_nothing_created_or_modified(): void
    {
        $this->runJson();

        $second = $this->runJson();

        $this->assertSame([], $second['created']);
        $this->assertSame([], $second['modified']);
        $this->assertSame([], $second['skipped']);
        $this->assertSame([], $second['unapplied']);
        $this->assertSame([], $second['conflicts']);
        $this->assertSame('', $second['diff']);
    }

    public function test_streams_lock_is_byte_identical_across_two_runs(): void
    {
        $this->runJson();

        $first = (string) file_get_contents(StreamLock::path($this->output));

        $this->runJson();

        $second = (string) file_get_contents(StreamLock::path($this->output));

        $this->assertSame($first, $second);

        $decoded = json_decode($first, true);
        $relative = 'app/Domains/People/Panel/Actions/PeopleActionsAdd.php';

        $this->assertIsArray($decoded);
        $this->assertArrayHasKey($relative, $decoded['people.actions.add']);
        $this->assertSame(
            StreamLock::hashContents(File::get($this->output.'/'.$relative)),
            $decoded['people.actions.add'][$relative],
        );
    }

    public function test_a_matching_lock_hash_is_replaced_when_the_tree_changes(): void
    {
        $this->runJson();

        $relative = 'app/Domains/People/Panel/Actions/PeopleActionsAdd.php';
        $absolute = $this->output.'/'.$relative;
        $before = File::get($absolute);

        $copy = $this->copyFixture();
        $actionFile = $copy.'/streams/people.actions.add.json';
        $action = json_decode((string) file_get_contents($actionFile), true);
        $action['label'] = 'Create person';
        file_put_contents($actionFile, json_encode($action, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n");

        $report = $this->runJson(['--tree' => $copy.'/streams.json']);
        $updated = File::get($absolute);

        $this->assertContains($relative, $report['modified']);
        $this->assertSame([], $report['conflicts']);
        $this->assertNotSame($before, $updated);
        $this->assertStringContainsString("#[Generated('people.actions.add')]", $updated);
        $this->assertStringContainsString("return 'Create person';", $updated);

        $lock = json_decode((string) file_get_contents(StreamLock::path($this->output)), true);

        $this->assertSame(StreamLock::hashContents($updated), $lock['people.actions.add'][$relative]);
    }

    public function test_a_deleted_lock_allows_tagged_files_to_be_rebuilt(): void
    {
        $this->assertMissingLockAllowsRebuild(true);
    }

    public function test_a_missing_lock_entry_allows_its_tagged_file_to_be_rebuilt(): void
    {
        $this->assertMissingLockAllowsRebuild(false);
    }

    protected function assertMissingLockAllowsRebuild(bool $deleteLock): void
    {
        $this->runJson();

        $relative = 'app/Domains/People/Panel/Actions/PeopleActionsAdd.php';
        $absolute = $this->output.'/'.$relative;
        $lockPath = StreamLock::path($this->output);

        if ($deleteLock) {
            File::delete($lockPath);
        } else {
            $lock = StreamLock::read($this->output);
            unset($lock->entries['people.actions.add'][$relative]);
            $lock->write($this->output);
        }

        $copy = $this->copyFixture();
        $actionFile = $copy.'/streams/people.actions.add.json';
        $action = json_decode((string) file_get_contents($actionFile), true);
        $action['label'] = 'Create person';
        file_put_contents($actionFile, json_encode($action, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n");

        $before = File::get($absolute);
        $lockBefore = is_file($lockPath) ? File::get($lockPath) : null;
        $dry = $this->runJson(['--tree' => $copy.'/streams.json', '--dry-run' => true]);

        $this->assertContains($relative, $dry['modified']);
        $this->assertSame([], $dry['conflicts']);
        $this->assertSame($before, File::get($absolute));
        $this->assertSame($lockBefore, is_file($lockPath) ? File::get($lockPath) : null);

        $real = $this->runJson(['--tree' => $copy.'/streams.json']);
        $updated = File::get($absolute);

        $this->assertSame($dry, $real);
        $this->assertStringContainsString("#[Generated('people.actions.add')]", $updated);
        $this->assertStringContainsString("return 'Create person';", $updated);
        $this->assertSame(StreamLock::hashContents($updated), StreamLock::read($this->output)->hash('people.actions.add', $relative));

        $lockAfter = File::get($lockPath);
        $second = $this->runJson(['--tree' => $copy.'/streams.json']);

        $this->assertSame([], $second['modified']);
        $this->assertSame([], $second['conflicts']);
        $this->assertSame($lockAfter, File::get($lockPath));
    }

    public function test_a_hand_edit_to_a_tagged_member_is_a_conflict_and_the_file_is_left_unchanged(): void
    {
        $this->runJson();

        $relative = 'app/Domains/People/Panel/Actions/PeopleActionsAdd.php';
        $absolute = $this->output.'/'.$relative;
        $original = File::get($absolute);
        $lockBefore = (string) file_get_contents(StreamLock::path($this->output));

        $this->assertStringContainsString("#[Generated('people.actions.add')]", $original);

        $edited = str_replace("return 'Add person';", "return 'Added by hand';", $original);

        $this->assertNotSame($original, $edited);
        File::put($absolute, $edited);

        $code = Artisan::call('streams:make', [
            '--tree' => $this->fixture,
            '--output' => $this->output,
            '--dry-run' => true,
        ]);
        $text = Artisan::output();

        $this->assertSame(0, $code, $text);
        $this->assertStringContainsString('conflict: people.actions.add '.$relative, $text);
        $this->assertSame($edited, File::get($absolute));
        $this->assertSame($lockBefore, (string) file_get_contents(StreamLock::path($this->output)));

        $dry = $this->runJson(['--dry-run' => true]);
        $real = $this->runJson();

        $this->assertSame($edited, File::get($absolute));
        $this->assertSame($lockBefore, (string) file_get_contents(StreamLock::path($this->output)));
        $this->assertNotContains($relative, $real['modified']);
        $this->assertNotContains($relative, $real['created']);
        $this->assertSame($dry['conflicts'], $real['conflicts']);

        $match = null;

        foreach ($real['conflicts'] as $conflict) {
            if ($conflict['path'] === 'people.actions.add' && $conflict['file'] === $relative) {
                $match = $conflict;
            }
        }

        $this->assertNotNull($match);
        $this->assertSame('people.actions.add', $match['path']);
        $this->assertSame($relative, $match['file']);
    }

    public function test_removing_a_node_leaves_its_file_and_lists_it_as_skipped(): void
    {
        $this->runJson();

        $action = 'app/Domains/People/Panel/Actions/PeopleActionsAdd.php';
        $absolute = $this->output.'/'.$action;
        $before = File::get($absolute);
        $beforeCount = count($this->phpFiles());

        $copy = $this->copyFixture();
        $peopleFile = $copy.'/streams/people.json';
        $people = json_decode((string) file_get_contents($peopleFile), true);
        unset($people['ui']['actions']);
        file_put_contents($peopleFile, json_encode($people, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

        $report = $this->runJson(['--tree' => $copy.'/streams.json']);

        $this->assertFileExists($absolute);
        $this->assertSame($before, File::get($absolute));
        $this->assertContains($action, $report['skipped']);
        $this->assertNotContains($action, $report['created']);
        $this->assertNotContains($action, $report['modified']);
        $this->assertGreaterThanOrEqual($beforeCount, count($this->phpFiles()));
        $this->assertSame([], $report['created']);
    }

    public function test_an_unapplied_edit_reports_path_file_and_reason_and_writes_nothing(): void
    {
        $this->runJson();

        $relative = 'app/Domains/People/Panel/Tables/PeopleTable.php';
        $absolute = $this->output.'/'.$relative;
        $broken = <<<'PHP'
<?php

namespace App\Domains\People\Panel\Tables;

/**
 * Generated by streams/sdk.
 * Node: people.table
 */

PHP;
        File::put($absolute, $broken);

        $dry = $this->runJson(['--dry-run' => true]);
        $this->assertSame($broken, File::get($absolute));

        $real = $this->runJson();

        $this->assertSame($dry['unapplied'], $real['unapplied']);
        $this->assertSame($broken, File::get($absolute));
        $this->assertNotContains($relative, $real['modified']);
        $this->assertNotContains($relative, $real['created']);

        $match = null;

        foreach ($real['unapplied'] as $edit) {
            if ($edit['path'] === 'people.table' && str_contains($edit['reason'], 'no class declaration')) {
                $match = $edit;
            }
        }

        $this->assertNotNull($match);
        $this->assertSame('people.table', $match['path']);
        $this->assertSame($relative, $match['file']);
        $this->assertStringContainsString('cannot apply edit [declare class PeopleTable]', $match['reason']);
    }

    public function test_no_separate_build_command_is_registered(): void
    {
        $names = array_keys(Artisan::all());

        $this->assertContains('streams:make', $names);
        $this->assertNotContains('streams:build', $names);

        foreach ($names as $name) {
            $this->assertFalse(str_starts_with($name, 'streams:build'), $name);
            $this->assertStringNotContainsString('make:page', $name);
            $this->assertStringNotContainsString('make:action', $name);
            $this->assertStringNotContainsString('make:form', $name);
        }
    }

    /**
     * @param  array<string, mixed>  $extra
     * @return array<string, mixed>
     */
    protected function runJson(array $extra = []): array
    {
        $code = Artisan::call('streams:make', array_merge([
            '--tree' => $this->fixture,
            '--output' => $this->output,
            '--json' => true,
        ], $extra));

        $output = Artisan::output();

        $this->assertSame(0, $code, $output);

        $decoded = json_decode($output, true);

        $this->assertIsArray($decoded, $output);
        $this->assertArrayHasKey('created', $decoded);
        $this->assertArrayHasKey('modified', $decoded);
        $this->assertArrayHasKey('skipped', $decoded);
        $this->assertArrayHasKey('unapplied', $decoded);
        $this->assertArrayHasKey('conflicts', $decoded);

        return $decoded;
    }

    /**
     * @return list<string>
     */
    protected function phpFiles(): array
    {
        if (! is_dir($this->output)) {
            return [];
        }

        $files = [];

        foreach (File::allFiles($this->output) as $file) {
            if ($file->getExtension() === 'php') {
                $files[] = $file->getRelativePathname();
            }
        }

        sort($files);

        return $files;
    }

    protected function copyFixture(): string
    {
        $dest = sys_get_temp_dir().'/streams-sdk-make-tree-'.uniqid();

        File::copyDirectory(dirname($this->fixture), $dest);

        $this->treeCopy = $dest;

        return $dest;
    }
}
